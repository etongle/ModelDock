"""Fetch the pinned, hash-verified portable Python distribution for packaging."""
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import tarfile
import tempfile
import urllib.request

project = Path(__file__).resolve().parent
lock = json.loads((project / 'Resources/python-runtime.json').read_text())
cache = project / 'build/runtime-cache'
cache.mkdir(parents=True, exist_ok=True)
archive = cache / ('python-' + lock['version'] + '-' + lock['release'] + '.tar.gz')

def digest(file):
    h = hashlib.sha256()
    with file.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''): h.update(block)
    return h.hexdigest()

if not archive.exists() or digest(archive) != lock['sha256']:
    temporary = archive.with_suffix('.download')
    for source in lock.get('mirrors', []) + [lock['url']]:
        try:
            request = urllib.request.Request(source, headers={'User-Agent': 'ModelManager-Packaging'})
            with urllib.request.urlopen(request, timeout=60) as incoming, temporary.open('wb') as outgoing:
                shutil.copyfileobj(incoming, outgoing)
            break
        except Exception:
            if source == lock['url']: raise
    if digest(temporary) != lock['sha256']:
        raise RuntimeError('Python archive checksum mismatch; not extracted')
    temporary.replace(archive)
target = cache / ('python-' + lock['version'] + '-' + lock['release'])
if not target.exists():
    stage = Path(tempfile.mkdtemp(prefix='extract-', dir=cache))
    try:
        with tarfile.open(archive) as bundle:
            for item in bundle.getmembers():
                name = PurePosixPath(item.name)
                if name.is_absolute() or '..' in name.parts or not name.parts or name.parts[0] != 'python':
                    raise RuntimeError('Unsafe Python archive path')
                if item.isdev() or item.isfifo(): raise RuntimeError('Unexpected special archive file')
                if item.issym() or item.islnk():
                    destination = (stage / item.name).parent / item.linkname if item.issym() else stage / item.linkname
                    if not str(destination.resolve()).startswith(str((stage / 'python').resolve()) + os.sep):
                        raise RuntimeError('Python archive link escapes runtime')
            bundle.extractall(stage)
        runtime = stage / 'python'
        # Keep the standard library, pip and licenses; generated bytecode is not needed.
        for folder in list(runtime.rglob('__pycache__')): shutil.rmtree(folder)
        runtime.rename(target)
    finally:
        shutil.rmtree(stage, ignore_errors=True)
assert (target / 'bin/python3').is_file()
print(target)
